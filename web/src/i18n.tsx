const dicts: Record<string, Dict> = { zh, en };

export type Locale = 'zh' | 'en';

interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18nCtx>({ locale: 'zh', setLocale: () => {}, t: (k) => k });

export function detectLocale(): Locale {
  const saved = localStorage.getItem('g4d_locale');
  if (saved === 'zh' || saved === 'en') return saved;
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem('g4d_locale', l);
  }, []);
  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let s = dicts[locale][key] ?? dicts.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      }
      return s;
    },
    [locale],
  );
  return <Ctx.Provider value={{ locale, setLocale, t }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  return useContext(Ctx);
}

export function relTime(ts: number | null | undefined, locale: Locale): string {
  if (!ts) return '—';
  const diff = Date.now() - ts;
  if (diff < 60_000) return locale === 'zh' ? '刚刚' : 'just now';
  if (diff < 3600_000) return locale === 'zh' ? `${Math.floor(diff / 60_000)} 分钟前` : `${Math.floor(diff / 60_000)}m ago`;
  if (diff < 86400_000) return locale === 'zh' ? `${Math.floor(diff / 3600_000)} 小时前` : `${Math.floor(diff / 3600_000)}h ago`;
  return locale === 'zh' ? `${Math.floor(diff / 86400_000)} 天前` : `${Math.floor(diff / 86400_000)}d ago`;
}

export function fmtDateTime(ts: number | null | undefined): string {
  if (!ts) return '—';
  const d = new Date(ts);
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

export function fmtTokens(n: number): string {
  if (n >= 1_000_000_000) return `${(n / 1_000_000_000).toFixed(1)}B`;
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}K`;
  return String(n);
}
